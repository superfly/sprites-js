// Writes src/version.ts from the version in package.json. It runs before
// every build, so a published package carries the version it was published
// as without reading its manifest at runtime, which fails once a bundler has
// moved the SDK away from it.
import { readFileSync, writeFileSync } from 'node:fs';

const manifest = new URL('../package.json', import.meta.url);
const target = new URL('../src/version.ts', import.meta.url);

const { version } = JSON.parse(readFileSync(manifest, 'utf8'));
const source = `// Generated by scripts/write-version.mjs. Do not edit.
export const VERSION = ${JSON.stringify(version)};
`;

let current;
try {
  current = readFileSync(target, 'utf8');
} catch {
  current = undefined;
}
if (current !== source) writeFileSync(target, source);
